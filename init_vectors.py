# 构建文本数据
for major, jobs in computer_data.items():
    for job, info in jobs.items():
        # 将技能字典转换为带描述的格式
        skills_list = []
        skills_with_desc = []
        for skill_name, skill_desc in info['skills'].items():
            skills_list.append(skill_name)
            skills_with_desc.append(f"{skill_name}:{skill_desc}")
        
        text = f"专业：{major} | 岗位：{job} | 描述：{info['description']} | 技能：{', '.join(skills_list)}"
        texts.append(text)
        metadatas.append({
            'level1': '计算机',
            'level2': major,
            'level3': job,
            'level3_desc': info['description'],
            'level4': ', '.join(skills_list),
            'level4_desc': '; '.join(skills_with_desc)  # 技能详细描述
        })

